const LANG_KEY = "koko.lang";
let LANG = (() => {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === "en" || saved === "ja") return saved;
  } catch { /* storage blocked: fall through */ }
  return (navigator.language || "en").toLowerCase().startsWith("ja") ? "ja" : "en";
})();

function t(key, vars = {}) {
  const s = STRINGS[LANG][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

function usageLabel(ja) {
  if (!ja) return t("bldg.unknown");
  return LANG === "ja" ? ja : (USAGE_EN[ja] || ja);
}

/* Apply static translations: data-i18n (HTML), data-i18n-placeholder, data-i18n-aria, data-i18n-q (chat prompts). */
function applyStaticI18n() {
  document.documentElement.lang = LANG;
  document.title = t("page.title");
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.innerHTML = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nAria)));
  document.querySelectorAll("[data-i18n-q]").forEach((el) => { el.dataset.q = t(el.dataset.i18nQ); });
  document.querySelectorAll(".lang-switch button").forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.lang === LANG)));
}

function setLang(lang) {
  if (lang === LANG) return;
  LANG = lang;
  try { localStorage.setItem(LANG_KEY, lang); } catch { /* storage blocked */ }
  applyStaticI18n();
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}

document.querySelectorAll(".lang-switch button").forEach((b) => b.addEventListener("click", () => setLang(b.dataset.lang)));
applyStaticI18n();
